"""###Train Model

* **Loss Function:**A function to measure how wrong your model's predictions are to the ideal outputs,lower is better.(Modelin hata oranını gösterir)(düşük değer=daha iyidir.)

* **Optimizer:**Takes into account the loss of a model and adjusts the model's parameters(e.g. weight & bias) to improve the loss function.

And specifically for PyTorch, we need

* A training loop
* A testing loop
"""

list(model_0.parameters())

model_0.state_dict()

loss_fn = nn.L1Loss()

#-> SGD Modelin tahminleri yanlış yaptığında, SGD weights ve bias değerlerini hatayı azaltacak yönde günceller.
optimizer=torch.optim.SGD (params=model_0.parameters(),
                           lr=0.01)# lr=learning rate

"""### Building a training loop (and a testing loop) in PyTorch

0- LOOP THROUGH THE DATA

1- FORWARD PASS (THIS INVOLVES DATA MOVING THROUGH ORU MODEL'S `forward()` to make predictions on data)


2- CALCULATE THE LOSS (COMPARE FORWARD PASS PREDICTIONS TO GROUND TRUTH LABELS)


3- OPTIMIZER ZERO GRAD


4- LOSS BACKWARD - MOVE BACKWARDS THROUGH THE NETWORK TO CALCULATE THE GRADİENTS OF EACH OF THE PARAMETERS OF OUR MODEL WITH RESPECT TO THE LOSS


5- OPTIMIZER STEP
"""

torch.manual_seed(42)

# An epoch is one loop through the data...
epochs = 100

epoch_count = []
loss_values = []
test_loss_values = []

#0- Loop through the data
for epoch in range(epochs):
  #Set the model to training mode
  model_0.train() # train mode in PyTorch set


  #1- Forward pass
  y_pred= model_0(X_train)

  #2- Calculate the loss
  loss = loss_fn(y_pred, Y_train)


  #3- Optimizer zero grad
  optimizer.zero_grad()

  #4- Perform backpropagation on the loss with respect to the parameters of the model
  loss.backward()

  #5- Step the optimizer
  optimizer.step()

  #Testing
  model_0.eval()
  with torch.inference_mode():

    test_pred=model_0(X_test)

    test_loss=loss_fn(test_pred,Y_test)

  if epoch % 10 == 0:
    epoch_count.append(epoch)
    loss_values.append(loss)
    test_loss_values.append(test_loss)
    print(f"Epoch: {epoch} | Loss: {loss} | Test Loss: {test_loss}")

    print(model_0.state_dict())

import numpy as np
np.array(torch.tensor(loss_values).cpu().numpy()),test_loss_values

plt.plot(epoch_count, np.array(torch.tensor(loss_values).cpu().numpy()), label= "Train Loss")
plt.plot(epoch_count, test_loss_values, label="Test Loss")
plt.title("Training and test loss curves")
plt.ylabel("Loss")
